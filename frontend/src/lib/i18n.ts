export const getGenreText = (slug: string | undefined, language: Language, fallbackName?: string, fallbackDescription?: string | null) => {
  if (slug && genreTranslations[slug]) return genreTranslations[slug][language];
  return {
    name: fallbackName ?? '',
    description: fallbackDescription ?? ''
  };
};

